#!/usr/bin/env python3
"""Generate manuscript numbers/table from existing CSV; never run simulations."""
import csv
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parents[1]
SRC = ROOT / 'iommu-platform/out/invalidation-interference-20261017/analysis/results.csv'
PLRU = ROOT / 'iommu-platform/out/plru-ablation-20261017/analysis/comparison.csv'
ML = ROOT / 'iommu-platform/out/dead-translation-20261017/analysis/final/results.csv'

def main():
    rows = list(csv.DictReader(SRC.open()))
    cases = {r['case_id']: r for r in rows}
    def row(mode, pages, domain='same', policy='full-api'):
        return cases[f'{domain}-b{pages}-{mode}-{policy}']
    def val(mode, pages, column, domain='same', policy='full-api'):
        return int(row(mode, pages, domain, policy)[column])
    macros = {}
    def put(name, value):
        macros[name] = str(value)
    slow = [(float(row('m1',p)['B_time_over_M0'])-1)*100 for p in (4,8)]
    penalty = [(val('m3',p,'A_complete_with_final_flush_steps') / val('m1',p,'A_complete_with_final_flush_steps')-1)*100 for p in (4,8)]
    put('BSlowMin',f'{min(slow):.1f}')
    put('BSlowMax',f'{max(slow):.1f}')
    put('APenaltyMin',f'{min(penalty):.1f}')
    put('APenaltyMax',f'{max(penalty):.1f}')
    for name,mode,col in [('BaseWalk','m0','B_walks'),('WideWalk','m1','B_walks'),('FineWalk','m3','B_walks'),('WideTime','m1','B_complete_steps'),('BaseTime','m0','B_complete_steps'),('FineTime','m3','B_complete_steps')]:
        for p in (4,8): put(name+('Four' if p==4 else 'Eight'), val(mode,p,col))
    put('WideA',val('m1',4,'A_complete_with_final_flush_steps'))
    put('FineAFour',val('m3',4,'A_complete_with_final_flush_steps'))
    put('FineAEight',val('m3',8,'A_complete_with_final_flush_steps'))
    put('AWalks',val('m1',4,'A_walks'))
    for p in (4,8):
        suffix='Four' if p==4 else 'Eight'
        put('UnmapWalk'+suffix,val('m1',p,'B_walks',policy='unmap-only'))
        put('UnmapTime'+suffix,val('m1',p,'B_complete_steps',policy='unmap-only'))
    for mode,prefix in [('m4-16','BatchSixteen'),('m4-64','BatchSixtyFour')]:
        put(prefix+'Inv',val(mode,4,'cq_iotinval'))
        put(prefix+'Fence',val(mode,4,'cq_iofence'))
        for p in (4,8): put(prefix+('Four' if p==4 else 'Eight'),f'{(float(row(mode,p)["B_time_over_M0"])-1)*100:.1f}')
    put('MainCases',len([r for r in rows if r['map_policy']=='full-api']))
    put('ControlCases',len([r for r in rows if r['map_policy']=='unmap-only']))
    ml=list(csv.DictReader(ML.open()))
    mi={r['case_id']:r for r in ml}
    def m(mode,p): return mi[f'same-b{p}-{mode}']
    for p in (4,8):
        suffix='Four' if p==4 else 'Eight'
        s=m('ml-strict',p)
        put('MLStrictB'+suffix,s['T_B'])
        put('MLStrictA'+suffix,s['A_final_flush_end'])
        put('MLStrictSlow'+suffix,f'{(float(s["T_B_over_m0"])-1)*100:.3f}')
        put('MLDead'+suffix,f'{float(m("ml-fq",p)["dead_average_slot_fraction"])*100:.3f}')
    fq=m('ml-fq',4)
    for macro,col in [('MLFQPeak','fq_peak'),('MLFQCapacity','fq_capacity'),('MLFQDrain','fq_drain_end'),('MLFQTimeout','fq_timeout_cycles')]: put(macro,fq[col])
    broad=mi['concurrent-different-b8-m1'];fine=mi['concurrent-different-b8-m2']
    for macro,col in [('DiagADelta','A_final_flush_end'),('DiagFlushDelta','A_wall_flush'),('DiagFetchDelta','A_flush_cq_fetch'),('DiagPTWDelta','A_wall_copy_pte'),('DiagOtherDelta','A_wall_copy_other'),('DiagHostDelta','A_wall_host')]:
        put(macro,int(fine[col])-int(broad[col]))
    plru=list(csv.DictReader(PLRU.open()))
    # Column names are deliberately validated by plot_plru.py; retain CSV input identity here.
    (PAPER/'data/numbers.tex').write_text('% Generated by scripts/prepare_data.py from existing CSV.\n'+''.join('\\newcommand{\\'+k+'}{'+v+'}\n' for k,v in macros.items()))
    lines=[r'\begin{tabular}{lrrr}',r'\toprule',r'Mode & IOTINVAL / fences & B walks & $T_A$ (cycles) \\',r' & & (4 / 8 pages) & (4 / 8 pages) \\',r'\midrule']
    for label,mode,domain in [('M0','m0','same'),('M1','m1','same'),('M2, different','m2','different'),('M3','m3','same'),('M4, $N=16$','m4-16','same'),('M4, $N=64$','m4-64','same')]:
        r=row(mode,4,domain)
        lines.append(f'{label} & {r["cq_iotinval"]} / {r["cq_iofence"]} & '+f'{val(mode,4,"B_walks",domain)} / {val(mode,8,"B_walks",domain)} & '+f'{val(mode,4,"A_complete_with_final_flush_steps",domain):,} / {val(mode,8,"A_complete_with_final_flush_steps",domain):,}'+r' \\')
    lines += [r'\bottomrule',r'\end{tabular}']
    (PAPER/'data/commands-table.tex').write_text('\n'.join(lines)+'\n')
    (PAPER/'data/numbers.json').write_text(json.dumps(macros,indent=2)+'\n')
    print(f'Generated {len(macros)} macros and table from {len(rows)} existing invalidation rows; PLRU input has {len(plru)} rows.')

if __name__=='__main__': main()
