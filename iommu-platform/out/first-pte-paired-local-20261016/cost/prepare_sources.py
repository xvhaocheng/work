#!/usr/bin/env python3
"""Prepare source-bound LOCAL synthesis cones; does not run Vivado."""
from pathlib import Path
import argparse
import hashlib
import json
import re


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
ROUND = HERE.parent
IDMA = ROOT / "iommu-platform/cva6/corev_apu/iDMA"
IOMMU = ROOT / "iommu-platform/cva6/corev_apu/riscv-iommu"
COMMON = ROOT / "iommu-platform/cva6/vendor/pulp-platform/common_cells"
AXI = ROOT / "iommu-platform/cva6/vendor/pulp-platform/axi"
OVER = ROUND / "o/files/iommu-platform/cva6/corev_apu"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def receipt(path, fragment, role, substitutions=None):
    text = path.read_text()
    offset = text.index(fragment)
    return {
        "role": role,
        "source": str(path.relative_to(ROOT)),
        "source_sha256": sha(path.read_bytes()),
        "first_line": text[:offset].count("\n") + 1,
        "last_line": text[:offset + len(fragment)].count("\n") + 1,
        "fragment_sha256": sha(fragment.encode()),
        "substitutions": substitutions or {},
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify outputs, without writing")
    args = parser.parse_args()
    generated = HERE / "generated"
    backend = OVER / "iDMA/src/idma_backend.sv"
    legalizer = OVER / "iDMA/src/idma_legalizer.sv"
    tc = OVER / "riscv-iommu/rtl/transaction_controller/rv_iommu_trans_ctl_wrap.sv"
    btext = backend.read_text()
    ttext = tc.read_text()
    receipts = []
    fixture = ROOT / "iommu-platform/tests/nonblock_actual_dma_top.sv"
    ftext = fixture.read_text()
    widths_start = ftext.index("    localparam int unsigned AxiAddrWidth")
    widths_end = ftext.index("\n\n", widths_start)
    receipts.append(receipt(fixture, ftext[widths_start:widths_end],
                            "actual fixture widths; backend request ID uses cfg/slave width6"))

    wanted = {"r_dp_req_t", "w_dp_req_t", "idma_r_req_t", "idma_w_req_t",
              "idma_mut_tf_opt_t", "idma_mut_tf_t"}
    typedefs = []
    for match in re.finditer(r"    typedef struct packed \{.*?\} (\w+);", btext, re.S):
        if match.group(1) in wanted:
            typedefs.append(match.group(0))
            receipts.append(receipt(backend, match.group(0), "backend typedef " + match.group(1)))
    if len(typedefs) != len(wanted):
        raise RuntimeError("backend typedef set changed; inspect before synthesizing")

    enum = re.search(r"    typedef enum logic \[2:0\] \{.*?\} trans_ctl_state_t;", ttext, re.S).group(0)
    receipts.append(receipt(tc, enum, "original TC state enum; boundary input, no new TC FF"))
    package = '''// Generated by prepare_sources.py; see source-map.json for source lines/hashes.
`include "idma/typedef.svh"
`include "axi-iommu/typedef.svh"
package o_cost_types;
  // Fixed actual fixture/backend dimensions, not measured board identity.
  localparam int DataWidth=64, AddrWidth=64, AxiIdWidth=2, UserWidth=1;
  localparam int TFLenWidth=64, StrbWidth=8, OffsetWidth=3;
  typedef logic [AddrWidth-1:0] addr_t;
  typedef logic [AxiIdWidth-1:0] id_t;
  typedef logic [UserWidth-1:0] user_t;
  typedef logic [OffsetWidth-1:0] offset_t;
  typedef logic [TFLenWidth-1:0] tf_len_t;
  typedef logic [5:0] cfg_id_t;
  typedef logic [23:0] did_t;
  typedef logic ssidv_t;
  typedef logic [19:0] ssid_t;
  `IDMA_TYPEDEF_FULL_REQ_T(idma_req_t, cfg_id_t, addr_t, tf_len_t)
  `AXI_TYPEDEF_AW_CHAN_EXT_T(aw_chan_t, addr_t, id_t, user_t, did_t, ssidv_t, ssid_t)
  `AXI_TYPEDEF_AR_CHAN_EXT_T(ar_chan_t, addr_t, id_t, user_t, did_t, ssidv_t, ssid_t)
''' + "\n\n".join(typedefs) + '''
  typedef logic [3:0] iommu_id_t;
  `AXI_TYPEDEF_AR_CHAN_EXT_T(iommu_ar_t, addr_t, iommu_id_t, user_t, did_t, ssidv_t, ssid_t)
''' + enum + "\nendpackage\n"

    b_start = btext.index("    assign r_ready = r_dp_req_in_ready & ar_ready &")
    b_end = btext.index("\n\n\n    //--------------------------------------\n    // Error handler", b_start)
    backend_piece = btext[b_start:b_end]
    receipts.append(receipt(backend, backend_piece,
                            "exact backend common-ready / prepared sticky generation"))
    l1_start = ttext.index("    assign first_pte_l1 =")
    l1_end = ttext.index("\n\n    always_comb begin : completion_bus", l1_start)
    l1_source = ttext[l1_start:l1_end]
    l1_piece = l1_source.replace("RVIOMMUCfg.AxiIdWidth", "IommuIdWidth")
    receipts.append(receipt(tc, l1_source, "TC L1 identity/hold equations",
                            {"RVIOMMUCfg.AxiIdWidth": "IommuIdWidth (fixed actual value 4)"}))
    c_start = ttext.index("            COMPLETE: begin", ttext.index("transaction_ctl_comb"))
    c_end = ttext.index("\n\n            default: begin", c_start)
    complete_piece = ttext[c_start:c_end]
    receipts.append(receipt(tc, complete_piece, "exact TC COMPLETE case branch"))

    top = '''// Generated source-bound local cost wrapper. No payload/RAM is instantiated.
// Same typed top ports for every policy and cone. Independent inputs keep
// both DMA legalizers and all candidate decisions observable.
module o_local_cost_top
  import o_cost_types::*;
#(
  parameter int unsigned FirstPteReadPolicy=0,
  // 0: two full actual legalizers only; 1: + actual backend and TC snippets.
  parameter int unsigned CostCone=0
)(
  input logic clk_i, rst_ni,
  input idma_req_t [1:0] req_i,
  input logic [1:0] valid_i,
  output logic [1:0] ready_o,
  output idma_r_req_t [1:0] r_req_o,
  output idma_w_req_t [1:0] w_req_o,
  output logic [1:0] r_valid_o, w_valid_o,
  input logic [1:0] r_ready_i, w_ready_i,
  input logic [1:0] flush_i, kill_i,
  input logic [1:0][1:0] ttype_i,
  output logic [1:0] r_busy_o, w_busy_o, pace_o,
  // Existing FIFO/holder boundaries; no new FIFO storage is synthesized.
  input logic [1:0] r_meta_in_ready_i, r_meta_out_valid_i, r_meta_out_ready_i,
  input r_dp_req_t [1:0] r_meta_head_i,
  input logic [1:0] ar_holder_ready_i,
  input logic [1:0] w_meta_in_ready_i, aw_holder_ready_i, w_last_ready_i,
  output logic [1:0] effective_r_ready_o, effective_w_ready_o, l0_done_o,
  // Existing A TC FIFO-head/state boundary, not a replacement TC or PA register.
  input iommu_ar_t tc_ar_head_i,
  input logic tc_ar_valid_i, tc_is_read_i, tc_is_write_i,
  input trans_ctl_state_t tc_state_i,
  input logic [1:0] fullbuffer_jobs_i,
  input logic tc_comp_ar_ready_i, tc_comp_aw_ready_i,
  output logic tc_l1_o, tc_hold_l1_o,
  output logic tc_complete_read_o, tc_complete_write_o,
  output logic tc_ar_pop_o, tc_aw_pop_o,
  output trans_ctl_state_t tc_state_n_o
);
  localparam int unsigned PairPolicy=FirstPteReadPolicy;
  for (genvar b=0; b<2; b++) begin : gen_dma
    localparam int unsigned FirstPteReadPolicy = (b==1 || PairPolicy==3) ? PairPolicy : 0;
    logic r_ready, w_ready, first_pte_pace;
    logic first_pte_l0_done_o;
    if (CostCone==1) begin : gen_backend_piece
      logic r_dp_req_in_ready, r_dp_req_out_valid, r_dp_req_out_ready;
      logic ar_ready, w_dp_req_in_ready, aw_ready, w_last_ready;
      logic req_valid, req_ready_o;
      r_dp_req_t r_dp_req_out;
      assign r_dp_req_in_ready=r_meta_in_ready_i[b];
      assign r_dp_req_out_valid=r_meta_out_valid_i[b];
      assign r_dp_req_out_ready=r_meta_out_ready_i[b];
      assign r_dp_req_out=r_meta_head_i[b];
      assign ar_ready=ar_holder_ready_i[b];
      assign w_dp_req_in_ready=w_meta_in_ready_i[b];
      assign aw_ready=aw_holder_ready_i[b];
      assign w_last_ready=w_last_ready_i[b];
      assign req_valid=valid_i[b];
      assign req_ready_o=ready_o[b];
''' + backend_piece + '''
    end else begin : gen_legalizer_boundary
      assign r_ready=r_ready_i[b];
      assign w_ready=w_ready_i[b];
      assign first_pte_l0_done_o=1'b0;
    end
    assign effective_r_ready_o[b]=r_ready;
    assign effective_w_ready_o[b]=w_ready;
    assign l0_done_o[b]=first_pte_l0_done_o;
    assign pace_o[b]=first_pte_pace;
    idma_legalizer #(
      .Protocol(idma_pkg::AXI), .DataWidth(DataWidth), .AddrWidth(AddrWidth),
      .FirstPteReadPolicy(FirstPteReadPolicy),
      .idma_req_t(idma_req_t), .idma_r_req_t(idma_r_req_t),
      .idma_w_req_t(idma_w_req_t), .idma_mut_tf_t(idma_mut_tf_t),
      .idma_mut_tf_opt_t(idma_mut_tf_opt_t)
    ) i_actual_legalizer (
      .clk_i, .rst_ni, .req_i(req_i[b]), .valid_i(valid_i[b]), .ready_o(ready_o[b]),
      .r_req_o(r_req_o[b]), .r_valid_o(r_valid_o[b]), .r_ready_i(r_ready),
      .first_pte_pace_o(first_pte_pace),
      .w_req_o(w_req_o[b]), .w_valid_o(w_valid_o[b]), .w_ready_i(w_ready),
      .flush_i(flush_i[b]), .kill_i(kill_i[b]),
      .r_busy_o(r_busy_o[b]), .w_busy_o(w_busy_o[b]), .ttype_i(ttype_i[b])
    );
  end
  if (CostCone==1) begin : gen_tc_piece
    localparam bit FirstPtePreparedEnable=(FirstPteReadPolicy==2);
    localparam int unsigned FirstPteAId=4, IommuIdWidth=4;
    localparam logic [23:0] FullBufferDID=24'd11;
    logic first_pte_l1, first_pte_hold_l1;
    logic fullbuffer_job_i, is_read, is_write, ar_valid, first_pte_l0_done_i;
    logic complete_read, complete_write, aw_ready, ar_ready;
    iommu_ar_t ar_data;
    trans_ctl_state_t state_q, state_n;
    // Projection of unchanged response fields used by the actual branch.
    struct packed {logic ar_ready; logic aw_ready;} axi_comp_resp;
    assign fullbuffer_job_i=fullbuffer_jobs_i[1];
    assign is_read=tc_is_read_i;
    assign is_write=tc_is_write_i;
    assign ar_valid=tc_ar_valid_i;
    assign ar_data=tc_ar_head_i;
    assign first_pte_l0_done_i=l0_done_o[1];
    assign axi_comp_resp.ar_ready=tc_comp_ar_ready_i;
    assign axi_comp_resp.aw_ready=tc_comp_aw_ready_i;
    assign state_q=tc_state_i;
''' + l1_piece + '''
    always_comb begin
      complete_read=1'b0;
      complete_write=1'b0;
      aw_ready=1'b0;
      ar_ready=1'b0;
      state_n=state_q;
      case (state_q)
''' + complete_piece + '''
        default: ;
      endcase
    end
    assign tc_l1_o=first_pte_l1;
    assign tc_hold_l1_o=first_pte_hold_l1;
    assign tc_complete_read_o=complete_read;
    assign tc_complete_write_o=complete_write;
    assign tc_ar_pop_o=ar_ready;
    assign tc_aw_pop_o=aw_ready;
    assign tc_state_n_o=state_n;
  end else begin : gen_no_tc_piece
    assign tc_l1_o=1'b0;
    assign tc_hold_l1_o=1'b0;
    assign tc_complete_read_o=1'b0;
    assign tc_complete_write_o=1'b0;
    assign tc_ar_pop_o=1'b0;
    assign tc_aw_pop_o=1'b0;
    assign tc_state_n_o=tc_state_i;
  end
endmodule
'''
    # These are copied unchanged; type extraction above adds no payload buffer.
    inputs = [legalizer, backend, tc, IDMA / "src/idma_pkg.sv",
              IDMA / "src/include/idma/typedef.svh", IDMA / "src/include/idma/guard.svh",
              IOMMU / "include/axi-iommu/typedef.svh", AXI / "src/axi_pkg.sv",
              AXI / "include/axi/typedef.svh",
              COMMON / "include/common_cells/registers.svh",
              COMMON / "include/common_cells/assertions.svh",
              ROOT / "iommu-platform/tests/nonblock_actual_dma_top.sv",
              ROOT / "iommu-platform/cva6/Makefile",
              ROUND / "m/files/tests/m_first_pte_gate.sv"]
    manifest = {
        "schema": "local-cost-source-extraction-v1",
        "task": "FIRST-PTE-PAIRED-LOCAL-1/local-cost",
        "source_files": [{"path": str(p.relative_to(ROOT)), "sha256": sha(p.read_bytes())} for p in inputs],
        "extractions": receipts,
        "dimensions": {"DataWidth":64,"AddrWidth":64,"TFLenWidth":64,"DmaAxiIdWidth":2,"CfgBusIDWidth":6,"IommuIdWidth":4,"AId":4,"AFullBufferDID":11},
        "constraints": {"part":"xc7k325tffg900-2","period_ns":20,"source":"iommu-platform/cva6/Makefile:65-67 (Genesys2 reference configuration)","actual_loaded_board_clock":"not_established_by_local_synthesis"},
        "cones": {"0":"two complete actual legalizers only","1":"cone0 plus actual backend pacing/sticky and TC comparator/COMPLETE fragments; existing FIFO/head/state boundaries external","m":"standalone actual M helper only; different scope"},
        "not_in_cost": ["fullbuffer certificate and source/mapping/pair qualification","wrapper option-rewrite mux and job FIFO timing","physical cross-layer routing and any extra pipeline","FIFO/head/PA storage or occupancy costs","M PTW exports and shared selector/arbiter integration","whole-system area/Fmax/service/latency"]
    }
    files = {generated / "o_cost_types.sv": package, generated / "o_local_cost_top.sv": top}
    manifest["generated_files"] = [{"path":str(p.relative_to(HERE)),"sha256":sha(s.encode())} for p,s in files.items()]
    files[HERE / "source-map.json"] = json.dumps(manifest,ensure_ascii=False,indent=2)+"\n"
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text()!=content:
                raise SystemExit("Generated source changed: "+str(path))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
    print("Source extraction verified." if args.check else "Prepared local source/type cones; Vivado was not run.")


if __name__ == "__main__":
    main()
